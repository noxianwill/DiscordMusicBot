import crypto from 'node:crypto';
import { EventEmitter } from 'node:events';
import { sendAgentRequest } from './rpc.js';

const ackEmitter = new EventEmitter();

export function handleAgentAck(msg) {
  if (msg.uploadId) {
    ackEmitter.emit(`ack:${msg.uploadId}`, msg.received);
  }
}

export async function streamUploadToAgent(agentWs, req, playlist, filename, overwrite = false) {
  const contentLength = Number(req.headers['content-length']);
  if (!contentLength || isNaN(contentLength)) {
    const err = new Error('Content-Length header required');
    err.code = 'BAD_REQUEST';
    throw err;
  }

  // 1. Begin upload
  const beginRes = await sendAgentRequest(agentWs, 'upload.begin', req.session.user.id, null, {
    playlist,
    filename,
    size: contentLength,
    overwrite
  });

  const uploadId = beginRes.uploadId;
  const uploadIdBuf = Buffer.from(uploadId, 'ascii');
  if (uploadIdBuf.length !== 36) {
    throw new Error('Invalid upload ID length generated by agent');
  }

  const hasher = crypto.createHash('sha256');
  const CHUNK_SIZE = 256 * 1024; // 256 KB
  const MAX_UNACK_BYTES = 4 * 1024 * 1024; // 4 MB backpressure threshold

  let totalSent = 0;
  let lastAcked = 0;
  let buffer = Buffer.alloc(0);

  const onAck = (received) => {
    lastAcked = received;
  };
  ackEmitter.on(`ack:${uploadId}`, onAck);

  try {
    for await (const rawChunk of req) {
      hasher.update(rawChunk);
      buffer = Buffer.concat([buffer, rawChunk]);

      while (buffer.length >= CHUNK_SIZE) {
        // Backpressure check
        while (totalSent - lastAcked > MAX_UNACK_BYTES) {
          await new Promise((resolve) => ackEmitter.once(`ack:${uploadId}`, resolve));
        }

        const chunkSlice = buffer.subarray(0, CHUNK_SIZE);
        buffer = buffer.subarray(CHUNK_SIZE);

        const frame = Buffer.concat([uploadIdBuf, chunkSlice]);
        agentWs.send(frame);
        totalSent += chunkSlice.length;
      }
    }

    // Send remaining bytes
    if (buffer.length > 0) {
      while (totalSent - lastAcked > MAX_UNACK_BYTES) {
        await new Promise((resolve) => ackEmitter.once(`ack:${uploadId}`, resolve));
      }
      const frame = Buffer.concat([uploadIdBuf, buffer]);
      agentWs.send(frame);
      totalSent += buffer.length;
      buffer = Buffer.alloc(0);
    }

    const sha256 = hasher.digest('hex');

    // 2. End upload
    const endRes = await sendAgentRequest(agentWs, 'upload.end', req.session.user.id, null, {
      uploadId,
      sha256
    }, 120000);

    return endRes;
  } catch (err) {
    // 3. Abort on error/client disconnect
    try {
      await sendAgentRequest(agentWs, 'upload.abort', req.session.user.id, null, { uploadId });
    } catch (_) {
      // Ignore errors on abort
    }
    throw err;
  } finally {
    ackEmitter.off(`ack:${uploadId}`, onAck);
  }
}

